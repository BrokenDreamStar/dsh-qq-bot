/**
 * 工具显示名：字典里有 `tool.<工具 id>` 就用它，否则原样返回工具 id
 * （新装的 dsh 插件、用户手填的通配条目都走这条回退）。**只是界面文案**：
 * 配置里保存的、模型调用的、CHAT_TOOLS 匹配的永远是工具 id。
 */
export function toolLabel(t: Translate, name: string): string {
	const key = `tool.${name}`;
	const label = t(key);
	return label === key ? name : label;
}

